from __future__ import annotations

import ast
from collections import Counter
from collections.abc import Iterable, Sequence
from pathlib import Path

from memory.importers.compatibility import EvidenceReference, ImporterCompatibility


class CompatibilityMatrixValidator:
    """Validate matrix coverage and local evidence without knowing how it is rendered."""

    def __init__(self, repository_root: Path, registered_importers: Iterable[str]) -> None:
        self._repository_root = repository_root
        self._registered_importers = frozenset(registered_importers)

    def validate(self, entries: Sequence[ImporterCompatibility]) -> tuple[str, ...]:
        errors: list[str] = []
        counts = Counter(entry.importer for entry in entries)
        duplicates = sorted(name for name, count in counts.items() if count != 1)
        if duplicates:
            errors.append(f"matrix entries must be unique: {', '.join(duplicates)}")

        matrix_names = frozenset(counts)
        missing = sorted(self._registered_importers - matrix_names)
        extra = sorted(matrix_names - self._registered_importers)
        if missing:
            errors.append(f"registered importers missing from matrix: {', '.join(missing)}")
        if extra:
            errors.append(f"matrix entries without registered importers: {', '.join(extra)}")

        for entry in entries:
            if bool(entry.verified_client_version) != bool(entry.verification_date):
                errors.append(
                    f"{entry.importer}: verified client version and date must be set together"
                )
            if not entry.fixtures:
                errors.append(f"{entry.importer}: at least one fixture is required")
            if not entry.tests:
                errors.append(f"{entry.importer}: at least one focused test is required")
            for reference in (*entry.fixtures, *entry.tests):
                errors.extend(self._validate_reference(entry.importer, reference))
        return tuple(errors)

    def _validate_reference(self, importer: str, reference: EvidenceReference) -> list[str]:
        path = self._repository_root / reference.path
        if not path.is_file():
            return [f"{importer}: missing evidence file: {reference.path}"]
        if reference.symbol is None:
            return []
        if path.suffix != ".py":
            return [f"{importer}: symbol reference is not a Python file: {reference.path}"]
        symbols = {
            node.name
            for node in ast.parse(path.read_text(encoding="utf-8")).body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        }
        if reference.symbol not in symbols:
            return [f"{importer}: missing symbol {reference.symbol} in {reference.path}"]
        return []


class CompatibilityMarkdownRenderer:
    """Render validated compatibility records into a deterministic report."""

    _HEADER = """# Importer Compatibility Matrix

<!-- Generated by tools/generate_importer_compatibility.py; do not edit directly. -->

This report records the repository evidence for every registered importer. A
documented export command means the export workflow is user-facing; it does not
promise that every future vendor version will retain the same shape. Observed
internal formats are compatibility baselines, not vendor contracts.

An **Unverified** client version means the fixtures exercise the stated format
envelope but do not establish compatibility with a particular upstream release.
Unknown or newer versions should be treated as unsupported until a minimized
synthetic or sanitized-derived fixture and focused test are added.

## Summary

| Importer | Source | Contract | Last verified upstream client | Verified on |
| --- | --- | --- | --- | --- |
"""

    def render(self, entries: Sequence[ImporterCompatibility]) -> str:
        ordered = sorted(entries, key=lambda entry: entry.importer)
        lines = [self._HEADER.rstrip()]
        for entry in ordered:
            lines.append(
                "| "
                + " | ".join(
                    (
                        self._code(entry.importer),
                        self._cell(entry.source),
                        self._cell(entry.contract.value),
                        self._cell(entry.verified_client_version or "Unverified"),
                        self._cell(entry.verification_date or "Not recorded"),
                    )
                )
                + " |"
            )

        lines.extend(("", "## Detailed evidence", ""))
        for entry in ordered:
            lines.extend(self._render_entry(entry))
        return "\n".join(lines).rstrip() + "\n"

    def _render_entry(self, entry: ImporterCompatibility) -> list[str]:
        return [
            f"### {entry.importer}",
            "",
            f"- **Source:** {entry.source}",
            f"- **Artifact or command:** {entry.artifact}",
            f"- **Default local location:** {entry.default_location}",
            f"- **Contract status:** {entry.contract.value}",
            "- **Last verified upstream client:** "
            + (entry.verified_client_version or "Unverified"),
            f"- **Verification date:** {entry.verification_date or 'Not recorded'}",
            f"- **Supported envelope:** {entry.supported_envelope}",
            f"- **Fixture evidence:** {self._references(entry.fixtures)}",
            f"- **Focused tests:** {self._references(entry.tests)}",
            f"- **Known omissions:** {entry.known_omissions}",
            f"- **Unknown-format fallback:** {entry.fallback}",
            "",
        ]

    @classmethod
    def _references(cls, references: Sequence[EvidenceReference]) -> str:
        rendered = []
        for reference in references:
            label = reference.path.replace("\\", "/")
            if reference.symbol:
                label = f"{label}::{reference.symbol}"
            rendered.append(cls._code(label))
        return ", ".join(rendered)

    @staticmethod
    def _cell(value: str) -> str:
        return value.replace("|", "\\|").replace("\n", " ")

    @staticmethod
    def _code(value: str) -> str:
        return f"`{value}`"
